-- Portable between PostgreSQL (production) and H2 in PostgreSQL mode (tests).

create table api_key (
    id           uuid primary key,
    name         varchar(100) not null,
    key_prefix   varchar(16)  not null,
    key_hash     varchar(64)  not null unique,
    created_at   timestamp with time zone not null,
    last_used_at timestamp with time zone,
    revoked_at   timestamp with time zone
);

create table device (
    id                uuid primary key,
    name              varchar(100) not null,
    token_prefix      varchar(16)  not null,
    token_hash        varchar(64)  not null unique,
    created_at        timestamp with time zone not null,
    revoked_at        timestamp with time zone,
    last_connected_at timestamp with time zone,
    last_seen_at      timestamp with time zone,
    battery_level     integer,
    charging          boolean,
    signal_level      integer,
    operator_name     varchar(100),
    network_type      varchar(30),
    app_version       varchar(30)
);

create table sms_message (
    id               uuid primary key,
    api_key_id       uuid         not null references api_key (id),
    client_reference varchar(100),
    recipient        varchar(16)  not null,
    -- Erased once the message is sent, failed or expired.
    body             varchar(1000),
    body_length      integer      not null,
    status           varchar(20)  not null,
    device_id        uuid references device (id),
    attempts         integer      not null default 0,
    failure_reason   varchar(200),
    created_at       timestamp with time zone not null,
    updated_at       timestamp with time zone not null,
    expires_at       timestamp with time zone not null,
    dispatched_at    timestamp with time zone,
    accepted_at      timestamp with time zone,
    sent_at          timestamp with time zone,
    delivered_at     timestamp with time zone,
    version          bigint       not null default 0,
    constraint uk_sms_message_client_reference unique (api_key_id, client_reference)
);

create index idx_sms_message_status_created on sms_message (status, created_at);
create index idx_sms_message_device_status on sms_message (device_id, status);
create index idx_sms_message_created on sms_message (created_at);

create table message_event (
    id         bigint generated by default as identity primary key,
    message_id uuid        not null references sms_message (id) on delete cascade,
    status     varchar(20) not null,
    device_id  uuid,
    detail     varchar(200),
    created_at timestamp with time zone not null
);

create index idx_message_event_message on message_event (message_id, id);
